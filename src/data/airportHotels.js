/** Busca hoteles por nombre sin distinguir mayúsculas, acentos ni espacios repetidos. */
export function findAirportHotel(query) {
  const normalize = value => value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");

  const target = normalize(query);
  return AIRPORT_HOTELS.find(hotel => normalize(hotel.name) === target) ?? null;
}
